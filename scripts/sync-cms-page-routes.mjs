#!/usr/bin/env node
/**
 * Extracts the CMS page slugs registered in src/routes.tsx and writes them to
 * functions/_lib/cmsPageRoutes.ts.
 *
 * Why generate instead of query: the middleware needs to know whether a request
 * is for a CMS page BEFORE it can decide to pre-hydrate database blocks. Asking
 * the database would add a round-trip to every non-asset request on the site,
 * including "/". A compile-time allowlist costs nothing.
 *
 * The file is committed so the middleware does no filesystem I/O at request
 * time. Modelled on scripts/seo-localised-locales.mjs.
 *
 * Usage:
 *   node scripts/sync-cms-page-routes.mjs           # write the file
 *   node scripts/sync-cms-page-routes.mjs --check   # fail if out of date
 */

import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const ROUTES = join(root, 'src/routes.tsx');
const OUT = join(root, 'functions/_lib/cmsPageRoutes.ts');

/** `<Route path="terms" element={<CMSRoutePage slug="terms" />} />` */
const SLUG_RE = /<CMSRoutePage\s+slug="([a-z0-9-]+)"/g;

function extractSlugs(source) {
  const slugs = new Set();
  for (const match of source.matchAll(SLUG_RE)) slugs.add(match[1]);
  return [...slugs].sort();
}

function render(slugs) {
  return `// AUTO-GENERATED by scripts/sync-cms-page-routes.mjs — do not edit.
//
// Slugs rendered by CMSRoutePage at a bare path, plus the /p/:slug route
// handled by Page.tsx. The middleware uses this to decide whether a request
// could be a CMS page without asking the database, which would otherwise mean
// a round-trip on every non-asset request including "/".
//
// Re-run the script when a CMS route is added or removed.

export const CMS_PAGE_SLUGS: readonly string[] = ${JSON.stringify(slugs, null, 2)
    .replace(/"/g, "'")
    .replace(/\n/g, '\n')} as const;

const SLUG_SET = new Set(CMS_PAGE_SLUGS);

/**
 * Resolves a locale-stripped path to the cms_pages slug it renders, or null.
 * Accepts both the bare form ("/terms") and the generic form ("/p/:slug").
 */
export function cmsPageSlugFor(basePath: string): string | null {
  const path = basePath.replace(/\\/+$/, '') || '/';
  const segments = path.split('/').filter(Boolean);

  if (segments.length === 1 && SLUG_SET.has(segments[0])) return segments[0];
  if (segments.length === 2 && segments[0] === 'p' && /^[a-z0-9-]+$/.test(segments[1])) {
    return segments[1];
  }
  return null;
}
`;
}

const source = readFileSync(ROUTES, 'utf8');
const slugs = extractSlugs(source);

if (slugs.length === 0) {
  console.error('sync-cms-page-routes: found no CMSRoutePage slugs — refusing to write.');
  process.exit(1);
}

const next = render(slugs);
const check = process.argv.includes('--check');

let current = '';
try {
  current = readFileSync(OUT, 'utf8');
} catch {
  /* first run */
}

if (current === next) {
  console.log(`sync-cms-page-routes: up to date (${slugs.length} slugs).`);
  process.exit(0);
}

if (check) {
  console.error('sync-cms-page-routes: functions/_lib/cmsPageRoutes.ts is out of date.');
  console.error('Run: node scripts/sync-cms-page-routes.mjs');
  process.exit(1);
}

writeFileSync(OUT, next);
console.log(`sync-cms-page-routes: wrote ${slugs.length} slugs to ${OUT}.`);
