#!/usr/bin/env node
/**
 * Generate the INSERT body for public.phone_country_rules from libphonenumber
 * metadata.
 *
 * Why generated rather than hand-written: turning a national number into
 * E.164 needs per-country facts a hand-maintained list gets wrong — the trunk
 * prefix is not always "0" (US "1", RU "8", HU "06"), Italy KEEPS its leading
 * 0 after +39, and what counts as a valid national number varies by country.
 * libphonenumber is the reference for all of it, so the table is a projection
 * of its metadata, regenerated when that metadata moves.
 *
 * Deliberately NOT an app dependency: libphonenumber-js is only needed to RUN
 * this script, never at runtime — the database applies the rules.
 *
 * Usage (from a scratch dir with `npm i libphonenumber-js`):
 *   node scripts/data-quality/generate-phone-rules.mjs --lib <path/to/node_modules/libphonenumber-js> > rules.sql
 */
import { createRequire } from 'node:module'
import path from 'node:path'

const args = process.argv.slice(2)
const libIdx = args.indexOf('--lib')
if (libIdx < 0 || !args[libIdx + 1]) {
  console.error('usage: generate-phone-rules.mjs --lib <path/to/libphonenumber-js>')
  process.exit(2)
}
const libDir = path.resolve(args[libIdx + 1])
const require = createRequire(path.join(libDir, 'package.json'))
const core = require(path.join(libDir, 'core'))
const meta = require(path.join(libDir, 'metadata.max.json'))
const version = require(path.join(libDir, 'package.json')).version

const q = (s) => (s == null ? 'null' : `'${String(s).replace(/'/g, "''")}'`)

const m = new core.Metadata(meta)
const rows = []
for (const country of core.getCountries(meta).sort()) {
  m.selectNumberingPlan(country)
  const p = m.numberingPlan
  // Every trunk prefix a national number may be written with. The canonical
  // one first, then the plain-digit alternatives libphonenumber accepts when
  // parsing (Lithuania writes "8 6…" as well as "0 6…", Belarus "8"/"80").
  // A parsing rule that is a real regex (carrier codes, area-code rewrites:
  // AR, BR, the Caribbean NANP members) is deliberately NOT translated —
  // such a number fails the pattern test and is preserved, not guessed.
  // Italy/SM/VA have NO national prefix in the metadata because their 0 is
  // part of the number, so the pattern test keeps it without a special case.
  const prefixes = []
  if (p.nationalPrefix()) prefixes.push(p.nationalPrefix())
  const forParsing = p.nationalPrefixForParsing() || ''
  let alts = []
  if (/^[0-9]+(\|[0-9]+)*$/.test(forParsing)) alts = forParsing.split('|')
  else if (/^\[[0-9]+\]$/.test(forParsing)) alts = forParsing.slice(1, -1).split('')
  else if (/^[0-9]+\|[0-9]+\?$/.test(forParsing)) {
    const [a, b] = forParsing.split('|')
    alts = [a, b.slice(0, -2), b.slice(0, -1)]
  }
  for (const a of alts) if (a && !prefixes.includes(a)) prefixes.push(a)
  // Longest first, so "80" is tried before "8".
  prefixes.sort((a, b) => b.length - a.length)
  const arr = prefixes.length ? `'{${prefixes.join(',')}}'` : `'{}'`
  rows.push(
    `  (${q(country)}, ${q(p.callingCode())}, ${arr}, ${q(p.nationalNumberPattern())}, ` +
      `'{${p.possibleLengths().join(',')}}', ${p.callingCode() && meta.country_calling_codes[p.callingCode()][0] === country})`,
  )
}

process.stdout.write(
  `-- Generated by scripts/data-quality/generate-phone-rules.mjs from libphonenumber-js ${version} metadata.max.json.\n` +
    `-- ${rows.length} countries. Do not edit by hand; regenerate.\n` +
    `insert into public.phone_country_rules (country_code, calling_code, national_prefixes, nsn_pattern, nsn_lengths, is_main_country) values\n` +
    rows.join(',\n') +
    `\non conflict (country_code) do update set\n` +
    `  calling_code = excluded.calling_code,\n` +
    `  national_prefixes = excluded.national_prefixes,\n` +
    `  nsn_pattern = excluded.nsn_pattern,\n` +
    `  nsn_lengths = excluded.nsn_lengths,\n` +
    `  is_main_country = excluded.is_main_country;\n`,
)
