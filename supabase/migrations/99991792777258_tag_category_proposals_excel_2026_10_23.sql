         count(*) filter (where not b.is_adult and t.is_adult)
    into v_lost, v_gained
  from _cp_adult_before b join public.unified_tags t on t.id = b.id;
  raise notice 'category proposals: % tags lost the 18+ gate, % gained it', v_lost, v_gained;
end
