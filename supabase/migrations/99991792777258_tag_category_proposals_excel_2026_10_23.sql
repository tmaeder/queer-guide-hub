do $verify$
declare v_rows int; v_applied int; v_bad int;
begin
  select count(*) into v_rows from _cp;
  select count(*) into v_applied from _cp_apply;
  -- END STATE, all three representations: the lever, the derived text and the
  -- primary junction row the tag page renders.
  select count(*) into v_bad
  from _cp_apply a join public.unified_tags t on t.id = a.id
  where t.category_id is distinct from a.new_id
     or t.category is distinct from a.new_name
     or not exists (select 1 from public.tag_category_assignments j
                    where j.tag_id = a.id and j.category_id = a.new_id and j.is_primary)
     or exists (select 1 from public.tag_category_assignments j
                where j.tag_id = a.id and j.category_id = a.old_id)
     or (select count(*) from public.tag_category_assignments j
         where j.tag_id = a.id and j.is_primary) <> 1;
  if v_bad <> 0 then
    raise exception 'category proposals: % rows do not carry the proposed category in all three representations, still hold the old membership, or lack exactly one primary', v_bad;
  end if;
  if v_applied < v_rows * 0.9 then
    raise exception 'category proposals: only % of % rows applied; the live corpus has drifted from the export', v_applied, v_rows;
  end if;
  raise notice 'category proposals applied to % of % rows', v_applied, v_rows;
end
$verify$;
