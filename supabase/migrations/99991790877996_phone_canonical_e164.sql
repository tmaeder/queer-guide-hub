-- Phone numbers: one stored format, +<calling code><national number> (E.164).
--
-- WHY A TRIGGER. venues.phone had ~20 writers (source-* fns, the patroc /
-- testfinder / aids-ch parsers, the CSV import, venue-contact-enrich,
-- venue-accessibility-osm, commit_venue_staging_item, the CMS editor) and none
-- of them normalised. Measured 2026-10-01 over 7,965 live venues with a phone:
-- ~1,250 national or human-formatted ("(415) 551-2500", "020 7452 3000"), and
-- of the 5,623 that LOOKED like E.164, 235 were wrong — the national trunk
-- prefix carried over behind the calling code ("+66 0 26370507",
-- "+32 0 25035918", "+86 0 1082863879"). organizations: 827 phones, 22 E.164.
-- Patching each writer leaves the next one open, so the format is enforced
-- where every write lands: a BEFORE trigger on venues, organizations, hotels.
--
-- WHY GENERATED RULES. Turning a national number into E.164 needs per-country
-- facts a hand list gets wrong: the trunk prefix is "0" in most of Europe but
-- "1" in NANP, "8" in Russia, "06" in Hungary, and Italy KEEPS its 0 after
-- +39. phone_country_rules is a projection of libphonenumber's metadata, made
-- by scripts/data-quality/generate-phone-rules.mjs — regenerate, never edit.
--
-- VALIDATED AGAINST libphonenumber, not by reading. The same algorithm was run
-- in JS beside libphonenumber-js over all 8,344 venue + organization phones
-- readable through the anon API: of the 8,045 both accept, 8,040 come out
-- byte-identical, and the 5 that differ are US numbers ("773-743-5772") on
-- venues whose country_id is wrong, which libphonenumber reads as German /
-- Finnish / Indian / British. The pattern used here is the per-country
-- general number pattern, a little looser than libphonenumber's per-type
-- check, so ~60 numbers in old national plans (pre-2021 Colombia, pre-ninth-
-- digit Brazil) are accepted rather than discarded — the FORMAT is still
-- uniform, which is what this file promises; dialability is not re-verified.
--
-- WHAT IS NOT CONVERTIBLE IS NOT GUESSED. ~260 venue numbers fail (wrong digit
-- count, two numbers concatenated, a calling code that does not exist). The
-- column is cleared — so it only ever holds the one format — and the original
-- value is kept on the row at enrichment_status.phone_rejected {raw, reason,
-- country, at}, so nothing is lost and a human can repair it.
-- needs_attention is deliberately NOT raised: that flag gates visibility on
-- some entities, and a bad phone number is no reason to unpublish a venue.

