-- ─── 3. The guard ────────────────────────────────────────────────────────────
-- UNSCOPED on purpose: country_id is often set by trg_*_geo_derive, which is
-- not in the UPDATE statement, and a column-scoped trigger fires on the
-- columns the STATEMENT names, not on what another BEFORE trigger wrote. The
-- name sorts after every geo-derivation and normalisation trigger on the three
-- tables (BEFORE triggers fire in name order), so it sees the final country.

create or replace function public.phone_canonical_guard()
returns trigger
language plpgsql
set search_path = public
as $fn$
declare
  v_cc  text;
  v_res jsonb;
begin
  -- Nothing to do when neither input moved — except under the backfill
  -- runner, which re-writes phone to itself precisely to come through here
  -- (a self-assignment changes no column, so without this flag every row it
  -- touches would return early and the backfill would report work it never
  -- did — exactly what the first prod dry run showed).
  if tg_op = 'UPDATE'
     and new.phone is not distinct from old.phone
     and new.country_id is not distinct from old.country_id
     and coalesce(current_setting('app.phone_recanonicalize', true), '') <> 'on' then
    return new;
  end if;

  if new.phone is null or btrim(new.phone) = '' then
    new.phone := null;
  else
    -- Always re-run, even on an E.164-shaped value: "+66026370507" has the
    -- right shape and a wrong trunk 0, and is exactly what this repairs.
    select code into v_cc from public.countries where id = new.country_id;
    v_res := public.canonicalize_phone(new.phone, v_cc);
    if v_res->>'verdict' = 'ok' then
      new.phone := v_res->>'e164';
    else
      new.enrichment_status := coalesce(new.enrichment_status, '{}'::jsonb)
        || jsonb_build_object('phone_rejected', jsonb_build_object(
             'raw', new.phone, 'reason', v_res->>'reason', 'country', v_cc, 'at', now()));
      new.phone := null;
    end if;
  end if;

  -- venues carries a second copy that trg_venues_normalized computed from the
  -- RAW value a moment earlier; keep the two in step.
  if tg_table_name = 'venues' then
    new.phone_e164 := new.phone;
  end if;
  return new;
end;
$fn$;

drop trigger if exists trg_venues_zz_phone_canonical on public.venues;
create trigger trg_venues_zz_phone_canonical
  before insert or update on public.venues
  for each row execute function public.phone_canonical_guard();

