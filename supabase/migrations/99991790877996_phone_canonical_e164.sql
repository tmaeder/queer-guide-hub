-- ─── 2. canonicalize_phone ───────────────────────────────────────────────────
-- Returns {verdict:'ok', e164, country, reason} or {verdict:'unparseable',
-- reason}; NULL for an empty input. Pure function of (raw, country, rules).

create or replace function public.canonicalize_phone(p_raw text, p_country_code text default null)
returns jsonb
language plpgsql
stable
set search_path = public
as $fn$
declare
  s        text;
  d        text;
  intl     boolean;
  r        record;
  us       record;
  cc       text;
  nsn      text;
  np       text;
  i        int;
  v_cc     text := upper(nullif(btrim(p_country_code), ''));
begin
  if p_raw is null or btrim(p_raw) = '' then
    return null;
  end if;

  s := btrim(p_raw);
  -- URL-encoded whitespace copied out of an href ("830%E2%80%AF0840").
  s := btrim(regexp_replace(s, '(%[0-9A-Fa-f]{2})+', ' ', 'g'));
  -- A label or URI scheme in front of the number.
  s := regexp_replace(s, '^(tel|phone|telefon|telephone|tél|fon|ph)\s*[.:]?\s*', '', 'i');
  -- Several numbers in one field: the first is the main line.
  s := btrim(split_part(regexp_replace(s, '\s+(or|oder|ou|o|y|und|and)\s+|[;,|]', ';', 'gi'), ';', 1));
  -- A trailing extension, and a bracketed note ("(only WhatsApp!)", "(de)").
  s := regexp_replace(s, '\s*(ext\.?|extension|x|#|durchwahl|dw\.?)\s*\d{1,6}\s*$', '', 'i');
  s := btrim(regexp_replace(s, '\s*\([^)]*[[:alpha:]][^)]*\)', '', 'g'));

  if s ~ '[[:alpha:]]' then
    return jsonb_build_object('verdict', 'unparseable', 'reason', 'letters');
  end if;

  -- "+41 (0)31 …": the bracketed trunk prefix is never dialled from abroad.
  s := replace(s, '(0)', '');
  -- "(+44) 0207 …": the plus may sit behind an opening bracket.
  intl := s ~ '^[^0-9]*\+';
  d := regexp_replace(s, '\D', '', 'g');
  -- "0049 …" and the doubled "+0049 …" both mean international.
  if d ~ '^00' then
    intl := true;
    d := substr(d, 3);
  end if;

  if length(d) < 5 or length(d) > 17 then
    return jsonb_build_object('verdict', 'unparseable', 'reason', 'length');
  end if;

  if intl then
    -- ITU calling codes are prefix-free, so at most one length has rules.
    for i in 1..3 loop
      cc  := left(d, i);
      nsn := substr(d, i + 1);
      for r in
        select * from public.phone_country_rules
         where calling_code = cc
         order by (country_code = v_cc) desc, is_main_country desc, country_code
      loop
        if nsn ~ ('^(?:' || r.nsn_pattern || ')$') then
          return jsonb_build_object('verdict', 'ok', 'e164', '+' || cc || nsn,
                                    'country', r.country_code, 'reason', 'international');
        end if;
        -- "+66 0 26370507": the trunk prefix carried over behind the calling
        -- code. Stripped only when what remains is a valid national number.
        foreach np in array r.national_prefixes loop
          if left(nsn, length(np)) = np
             and substr(nsn, length(np) + 1) ~ ('^(?:' || r.nsn_pattern || ')$') then
            return jsonb_build_object('verdict', 'ok', 'e164', '+' || cc || substr(nsn, length(np) + 1),
                                      'country', r.country_code, 'reason', 'stripped_trunk_prefix');
          end if;
        end loop;
      end loop;
    end loop;
    return jsonb_build_object('verdict', 'unparseable', 'reason', 'invalid_for_calling_code');
  end if;

  -- National form: only the row's own country can say what it means.
  select * into r from public.phone_country_rules where country_code = v_cc;
  if not found then
    return jsonb_build_object('verdict', 'unparseable', 'reason', 'no_country');
  end if;

  -- "773-743-5772" on a row whose country is not the US: the North American
  -- layout is unambiguous, and read as a national number of the row's own
  -- country it parses into something wrong (+49 773…, +353 818…). Those rows
  -- carry a wrong country_id; that is a geo defect, and the number itself is
  -- still dialled as +1. Hyphen/dot separators only — a space-separated
  -- "333 123 4567" is an Italian mobile.
  if r.country_code <> 'US'
     and s ~ '^(\([2-9][0-9]{2}\) ?|[2-9][0-9]{2}[-.])[2-9][0-9]{2}[-.][0-9]{4}$' then
    select * into us from public.phone_country_rules where country_code = 'US';
    if d ~ ('^(?:' || us.nsn_pattern || ')$') then
      return jsonb_build_object('verdict', 'ok', 'e164', '+1' || d,
                                'country', 'US', 'reason', 'nanp_layout');
    end if;
  end if;

  foreach np in array r.national_prefixes loop
    if left(d, length(np)) = np
       and substr(d, length(np) + 1) ~ ('^(?:' || r.nsn_pattern || ')$') then
      return jsonb_build_object('verdict', 'ok', 'e164', '+' || r.calling_code || substr(d, length(np) + 1),
                                'country', r.country_code, 'reason', 'national');
    end if;
  end loop;
  if d ~ ('^(?:' || r.nsn_pattern || ')$') then
    return jsonb_build_object('verdict', 'ok', 'e164', '+' || r.calling_code || d,
                              'country', r.country_code, 'reason', 'national_no_prefix');
  end if;
  -- International form written without its "+".
  if left(d, length(r.calling_code)) = r.calling_code
     and substr(d, length(r.calling_code) + 1) ~ ('^(?:' || r.nsn_pattern || ')$') then
    return jsonb_build_object('verdict', 'ok', 'e164', '+' || d,
                              'country', r.country_code, 'reason', 'missing_plus');
  end if;

  return jsonb_build_object('verdict', 'unparseable', 'reason', 'invalid_national');
end;
$fn$;

comment on function public.canonicalize_phone(text, text) is
  'Canonicalises a phone number to E.164 (+<calling code><number>, no separators) using phone_country_rules. Returns {verdict, e164, country, reason}. p_country_code (ISO2) is used only for numbers written in national form.';

