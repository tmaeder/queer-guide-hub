-- ─── 4. Backfill runner ──────────────────────────────────────────────────────
-- Keyset-paged over ids so it terminates and can resume: each call scans the
-- next p_batch rows with a phone after p_after and rewrites only those whose
-- stored value differs from its canonical form (a shape test alone would miss
-- the "+66 0 …" rows, which already look like E.164). Writing phone to itself
-- is enough — the guard does the work. Batched because a venues UPDATE runs
-- the spine/search chain per row.

create or replace function public.run_phone_canonical_backfill(
  p_table text, p_after uuid default null, p_batch int default 300)
returns jsonb
language plpgsql
security definer
set search_path = public
as $fn$
declare
  v_updated int;
  v_last    uuid;
begin
  if p_table not in ('venues', 'organizations', 'hotels') then
    raise exception 'unsupported table %', p_table using errcode = '22023';
  end if;

  execute format(
    'select max(id::text)::uuid from (
       select id from public.%I
        where phone is not null and ($1 is null or id > $1)
        order by id limit $2) w', p_table)
    into v_last using p_after, least(greatest(p_batch, 1), 1000);

  if v_last is null then
    return jsonb_build_object('table', p_table, 'updated', 0, 'next', null, 'done', true);
  end if;

  -- Transaction-local: read by phone_canonical_guard() only.
  perform set_config('app.phone_recanonicalize', 'on', true);

  execute format(
    'update public.%1$I t set phone = t.phone
       from (select w.id, c.code
               from public.%1$I w
               left join public.countries c on c.id = w.country_id
              where w.phone is not null
                and ($1 is null or w.id > $1) and w.id <= $2) s
      where t.id = s.id
        and t.phone is distinct from coalesce(public.canonicalize_phone(t.phone, s.code)->>''e164'', '''')', p_table)
    using p_after, v_last;
  get diagnostics v_updated = row_count;
  perform set_config('app.phone_recanonicalize', 'off', true);

  return jsonb_build_object('table', p_table, 'updated', v_updated, 'next', v_last, 'done', false);
end;
$fn$;

