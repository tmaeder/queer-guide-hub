DO $isolate$
DECLARE
  m record;
  f record;
  call_args text;
  signature text;
  impl_signature text;
  wrapper_body text;
  existing_comment text;
BEGIN
  FOR m IN SELECT * FROM pg_temp.rpc_hardening_manifest ORDER BY name, args LOOP
    SELECT p.*, pg_get_function_arguments(p.oid) AS full_args,
      pg_get_function_identity_arguments(p.oid) AS identity_args,
      pg_get_function_result(p.oid) AS return_type,
      obj_description(p.oid, 'pg_proc') AS description
    INTO f
    FROM pg_proc p JOIN pg_namespace n ON n.oid = p.pronamespace
    WHERE n.nspname = 'public' AND p.proname = m.name
      AND pg_get_function_identity_arguments(p.oid) = m.args;
    IF NOT FOUND THEN
      RAISE EXCEPTION 'Missing reviewed function: %(%)', m.name, m.args;
    END IF;
    IF NOT f.prosecdef OR f.prokind <> 'f' OR f.provariadic <> 0 THEN
      RAISE EXCEPTION 'Unexpected function definition: %(%)', m.name, m.args;
    END IF;
    signature := format('public.%I(%s)', f.proname, f.identity_args);
    IF m.backend_only THEN
      EXECUTE format('REVOKE EXECUTE ON FUNCTION %s FROM PUBLIC, anon, authenticated', signature);
      EXECUTE format('GRANT EXECUTE ON FUNCTION %s TO service_role', signature);
      CONTINUE;
    END IF;
    IF EXISTS (
      SELECT 1 FROM pg_proc p JOIN pg_namespace n ON n.oid = p.pronamespace
      WHERE n.nspname = 'api_private' AND p.proname = f.proname
        AND p.proargtypes = f.proargtypes
    ) THEN
      RAISE EXCEPTION 'Private function collision: %', signature;
    END IF;

    -- ALTER preserves the original OID, policy/view dependencies, owner, body,
    -- search_path and all function attributes. Do not DROP the implementation.
    EXECUTE format('ALTER FUNCTION %s SET SCHEMA api_private', signature);
    impl_signature := format('api_private.%I(%s)', f.proname, f.identity_args);
    EXECUTE format('REVOKE EXECUTE ON FUNCTION %s FROM PUBLIC, anon, authenticated', impl_signature);
    EXECUTE format('GRANT EXECUTE ON FUNCTION %s TO service_role', impl_signature);
    SELECT coalesce(string_agg(CASE WHEN coalesce(f.proargnames[i], '') <> '' THEN format('%I => $%s', f.proargnames[i], i) ELSE format('$%s', i) END, ', ' ORDER BY i), '')
      INTO call_args FROM generate_series(1, f.pronargs) i;
    wrapper_body := format('SELECT %sapi_private.%I(%s)',
      CASE WHEN f.proretset THEN '* FROM ' ELSE '' END, f.proname, call_args);
    EXECUTE format(
      'CREATE FUNCTION public.%I(%s) RETURNS %s LANGUAGE sql %s %s SECURITY INVOKER PARALLEL %s COST %s %s SET search_path = %L AS %L',
      f.proname, f.full_args, f.return_type,
      CASE f.provolatile WHEN 'i' THEN 'IMMUTABLE' WHEN 's' THEN 'STABLE' ELSE 'VOLATILE' END,
      CASE WHEN f.proisstrict THEN 'STRICT' ELSE 'CALLED ON NULL INPUT' END,
      CASE f.proparallel WHEN 's' THEN 'SAFE' WHEN 'r' THEN 'RESTRICTED' ELSE 'UNSAFE' END,
      f.procost,
      CASE WHEN f.proretset THEN format('ROWS %s', f.prorows) ELSE '' END,
      '', wrapper_body);
    -- Public-schema default ACLs can grant browser roles automatically.
    EXECUTE format('REVOKE EXECUTE ON FUNCTION %s FROM PUBLIC, anon, authenticated', signature);
    EXECUTE format('GRANT EXECUTE ON FUNCTION %s TO service_role', signature);
    IF m.allow_anon THEN
      EXECUTE format('GRANT EXECUTE ON FUNCTION %s, %s TO anon', signature, impl_signature);
    END IF;
    IF m.allow_authenticated THEN
      EXECUTE format('GRANT EXECUTE ON FUNCTION %s, %s TO authenticated', signature, impl_signature);
    END IF;
    existing_comment := coalesce(f.description || E'\n\n', '') ||
      'Invoker API entry point; privileged implementation in api_private. Authorization is enforced by the implementation.';
    EXECUTE format('COMMENT ON FUNCTION %s IS %L', signature, existing_comment);
  END LOOP;
END
$isolate$;

DO $verify$
DECLARE m record; f record;
BEGIN
  FOR m IN SELECT * FROM pg_temp.rpc_hardening_manifest LOOP
    SELECT p.oid, p.prosecdef INTO STRICT f
    FROM pg_proc p JOIN pg_namespace n ON n.oid=p.pronamespace
    WHERE n.nspname='public' AND p.proname=m.name
      AND pg_get_function_identity_arguments(p.oid)=m.args;
    IF m.backend_only THEN
      IF has_function_privilege('anon', f.oid, 'EXECUTE')
        OR has_function_privilege('authenticated', f.oid, 'EXECUTE') THEN
        RAISE EXCEPTION 'Backend function still exposed: %', m.name;
      END IF;
    ELSE
      IF f.prosecdef
        OR has_function_privilege('anon', f.oid, 'EXECUTE') <> m.allow_anon
        OR has_function_privilege('authenticated', f.oid, 'EXECUTE') <> m.allow_authenticated THEN
        RAISE EXCEPTION 'Invoker API contract changed: %', m.name;
      END IF;
    END IF;
    IF NOT has_function_privilege('service_role', f.oid, 'EXECUTE') THEN
      RAISE EXCEPTION 'Service access lost: %', m.name;
    END IF;
  END LOOP;
  IF EXISTS (
    SELECT 1 FROM pg_proc p JOIN pg_namespace n ON n.oid=p.pronamespace
    WHERE n.nspname='public' AND p.prosecdef
      AND (has_function_privilege('anon',p.oid,'EXECUTE')
        OR has_function_privilege('authenticated',p.oid,'EXECUTE'))
  ) THEN
    RAISE EXCEPTION 'Unexpected callable public SECURITY DEFINER function remains';
  END IF;
END
$verify$;
