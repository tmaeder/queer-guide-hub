-- Keep privileged implementations outside the Data API. Public entry points
-- retain their signatures and existing authorization checks, but run as invoker.
-- This is API isolation, not removal of the underlying RLS bypass: intentional
-- definer implementations still need their existing ownership/role checks.
-- Backend selectors and repair helpers have no browser callers; service clients
-- and postgres cron jobs retain EXECUTE on their existing public entry points.
SET LOCAL search_path = public, extensions, pg_catalog;
SET LOCAL lock_timeout = '5s';
CREATE SCHEMA IF NOT EXISTS api_private AUTHORIZATION postgres;
REVOKE ALL ON SCHEMA api_private FROM PUBLIC, anon, authenticated;
GRANT USAGE ON SCHEMA api_private TO anon, authenticated, service_role;
ALTER DEFAULT PRIVILEGES FOR ROLE postgres IN SCHEMA api_private
  REVOKE EXECUTE ON FUNCTIONS FROM PUBLIC, anon, authenticated;

